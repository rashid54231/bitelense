/// Screen presenting AI meal analysis with full user editing, portion rescaling,
/// and Save / Discard actions.
class ResultScreen extends ConsumerStatefulWidget {
  final ScanAnalysis initialAnalysis;
  final String imagePath;
  final File? localFile;

  const ResultScreen({
    super.key,
    required this.initialAnalysis,
    required this.imagePath,
    this.localFile,
  });

  @override
  ConsumerState<ResultScreen> createState() => _ResultScreenState();
}

class _ResultScreenState extends ConsumerState<ResultScreen> {
  late String _mealType;
  late List<MealItem> _items;
  late String _confidence;
  bool _isSaving = false;

  @override
  void initState() {
    super.initState();
    _mealType = widget.initialAnalysis.mealType;
    _items = List.from(widget.initialAnalysis.items);
    _confidence = widget.initialAnalysis.confidence;
  }

  double get _totalCalories =>
      _items.fold(0.0, (acc, item) => acc + item.calories);
  double get _totalProtein =>
      _items.fold(0.0, (acc, item) => acc + item.proteinG);
  double get _totalCarbs =>
      _items.fold(0.0, (acc, item) => acc + item.carbsG);
  double get _totalFat =>
      _items.fold(0.0, (acc, item) => acc + item.fatG);
  double get _totalFiber =>
      _items.fold(0.0, (acc, item) => acc + item.fiberG);

  Future<void> _saveMeal() async {
    final user = ref.read(currentUserProvider);
    if (user == null) {
      context.go('/auth');
      return;
    }

    if (_items.isEmpty) {
      AppSnackbar.showError(context, 'Please add at least one meal item.');
      return;
    }

    setState(() => _isSaving = true);

    try {
      final meal = Meal(
        id: '', // Generated by Supabase gen_random_uuid()
        userId: user.id,
        imagePath: widget.imagePath,
        mealType: _mealType,
        items: _items,
        totalCalories: _totalCalories.roundToDouble(),
        totalProteinG: (_totalProtein * 10).round() / 10.0,
        totalCarbsG: (_totalCarbs * 10).round() / 10.0,
        totalFatG: (_totalFat * 10).round() / 10.0,
        totalFiberG: (_totalFiber * 10).round() / 10.0,
        confidence: _confidence,
        userEdited: true,
        eatenAt: DateTime.now(),
      );

      await ref.read(todayMealsProvider.notifier).addMeal(meal);

      if (!mounted) return;
      AppSnackbar.showSuccess(context, AppStrings.mealSavedSuccess);
      context.go('/home');
    } catch (e) {
      if (mounted) {
        AppSnackbar.showError(context, 'Failed to save meal: $e');
      }
    } finally {
      if (mounted) setState(() => _isSaving = false);
    }
  }

  Future<void> _discardMeal() async {
    final confirmed = await showDialog<bool>(
      context: context,
      builder: (ctx) => AlertDialog(
        title: const Text('Discard Meal?'),
        content: const Text('This will delete the photo and discard the analysis.'),
        actions: [
          TextButton(
            onPressed: () => Navigator.pop(ctx, false),
            child: const Text('Keep'),
          ),
          TextButton(
            onPressed: () => Navigator.pop(ctx, true),
            child: const Text('Discard', style: TextStyle(color: AppColors.error)),
          ),
        ],
      ),
    );

    if (confirmed == true) {
      await ref.read(scanRepoProvider).deleteUploadedPhoto(widget.imagePath);
      if (mounted) {
        context.go('/home');
      }
    }
  }

  void _editItemDialog(int index) {
    final item = _items[index];
    final nameCtrl = TextEditingController(text: item.name);
    final portionCtrl = TextEditingController(text: item.portionText);
    double grams = item.gramsEstimate;
    final originalGrams = item.gramsEstimate;

    showModalBottomSheet(
      context: context,
      isScrollControlled: true,
      backgroundColor: Theme.of(context).scaffoldBackgroundColor,
      shape: const RoundedRectangleBorder(
        borderRadius: BorderRadius.vertical(top: Radius.circular(24)),
      ),
      builder: (ctx) => StatefulBuilder(
        builder: (ctx, setSheetState) {
          final rescaled = CalorieCalculator.rescaleNutrients(
            originalGrams: originalGrams,
            newGrams: grams,
            calories: item.calories,
            protein: item.proteinG,
            carbs: item.carbsG,
            fat: item.fatG,
            fiber: item.fiberG,
          );

          return Padding(
            padding: EdgeInsets.only(
              left: 20,
              right: 20,
              top: 20,
              bottom: MediaQuery.of(ctx).viewInsets.bottom + 20,
            ),
            child: Column(
              mainAxisSize: MainAxisSize.min,
              crossAxisAlignment: CrossAxisAlignment.stretch,
              children: [
                Row(
                  mainAxisAlignment: MainAxisAlignment.spaceBetween,
                  children: [
                    Text(AppStrings.editItem, style: AppTextStyles.titleMedium(ctx)),
                    IconButton(
                      icon: const Icon(Icons.delete_outline_rounded, color: AppColors.error),
                      onPressed: () {
                        setState(() => _items.removeAt(index));
                        Navigator.pop(ctx);
                      },
                    ),
                  ],
                ),
                const SizedBox(height: 16),
                TextField(
                  controller: nameCtrl,
                  decoration: const InputDecoration(labelText: AppStrings.itemName),
                ),
                const SizedBox(height: 14),
                TextField(
                  controller: portionCtrl,
                  decoration: const InputDecoration(labelText: AppStrings.portion),
                ),
                const SizedBox(height: 16),
                Row(
                  mainAxisAlignment: MainAxisAlignment.spaceBetween,
                  children: [
                    const Text('Portion Weight:', style: TextStyle(fontWeight: FontWeight.w600)),
                    Text(
                      '${grams.round()}g',
                      style: const TextStyle(fontWeight: FontWeight.w700, color: AppColors.primaryGreen),
                    ),
                  ],
                ),
                Slider(
                  value: grams.clamp(20.0, 800.0),
                  min: 20,
                  max: 800,
                  divisions: 78,
                  activeColor: AppColors.primaryGreen,
                  onChanged: (val) {
                    setSheetState(() => grams = val);
                  },
                ),
                const SizedBox(height: 8),
                Row(
                  mainAxisAlignment: MainAxisAlignment.spaceAround,
                  children: [
                    Text('${rescaled['calories'].round()} kcal', style: const TextStyle(fontWeight: FontWeight.w700)),
                    Text('P: ${rescaled['protein_g']}g', style: const TextStyle(color: AppColors.proteinColor)),
                    Text('C: ${rescaled['carbs_g']}g', style: const TextStyle(color: AppColors.carbsColor)),
                    Text('F: ${rescaled['fat_g']}g', style: const TextStyle(color: AppColors.fatColor)),
                  ],
                ),
                const SizedBox(height: 20),
                GradientButton(
                  text: 'Update Item',
                  onPressed: () {
                    setState(() {
                      _items[index] = item.copyWith(
                        name: nameCtrl.text.trim(),
                        portionText: portionCtrl.text.trim(),
                        gramsEstimate: grams,
                        calories: (rescaled['calories'] as num).toDouble(),
                        proteinG: (rescaled['protein_g'] as num).toDouble(),
                        carbsG: (rescaled['carbs_g'] as num).toDouble(),
                        fatG: (rescaled['fat_g'] as num).toDouble(),
                        fiberG: (rescaled['fiber_g'] as num).toDouble(),
                      );
                    });
                    Navigator.pop(ctx);
                  },
                ),
              ],
            ),
          );
        },
      ),
    );
  }

  void _addItemDialog() {
    final nameCtrl = TextEditingController();
    final portionCtrl = TextEditingController(text: '1 cup / serving');
    final calCtrl = TextEditingController(text: '200');
    final pCtrl = TextEditingController(text: '10');
    final cCtrl = TextEditingController(text: '25');
    final fCtrl = TextEditingController(text: '6');

    showModalBottomSheet(
      context: context,
      isScrollControlled: true,
      backgroundColor: Theme.of(context).scaffoldBackgroundColor,
      shape: const RoundedRectangleBorder(
        borderRadius: BorderRadius.vertical(top: Radius.circular(24)),
      ),
      builder: (ctx) => Padding(
        padding: EdgeInsets.only(
          left: 20,
          right: 20,
          top: 20,
          bottom: MediaQuery.of(ctx).viewInsets.bottom + 20,
        ),
        child: Column(
          mainAxisSize: MainAxisSize.min,
          crossAxisAlignment: CrossAxisAlignment.stretch,
          children: [
            Text(AppStrings.addItem, style: AppTextStyles.titleMedium(ctx)),
            const SizedBox(height: 14),
            TextField(
              controller: nameCtrl,
              decoration: const InputDecoration(labelText: 'Dish Name (e.g. Samosa, Naan, Chai)'),
            ),
            const SizedBox(height: 12),
            TextField(
              controller: portionCtrl,
              decoration: const InputDecoration(labelText: AppStrings.portion),
            ),
            const SizedBox(height: 12),
            Row(
              children: [
                Expanded(
                  child: TextField(
                    controller: calCtrl,
                    keyboardType: TextInputType.number,
                    decoration: const InputDecoration(labelText: 'Calories (kcal)'),
                  ),
                ),
                const SizedBox(width: 10),
                Expanded(
                  child: TextField(
                    controller: pCtrl,
                    keyboardType: TextInputType.number,
                    decoration: const InputDecoration(labelText: 'Protein (g)'),
                  ),
                ),
              ],
            ),
            const SizedBox(height: 12),
            Row(
              children: [
                Expanded(
                  child: TextField(
                    controller: cCtrl,
                    keyboardType: TextInputType.number,
                    decoration: const InputDecoration(labelText: 'Carbs (g)'),
                  ),
                ),
                const SizedBox(width: 10),
                Expanded(
                  child: TextField(
                    controller: fCtrl,
                    keyboardType: TextInputType.number,
                    decoration: const InputDecoration(labelText: 'Fat (g)'),
                  ),
                ),
              ],
            ),
            const SizedBox(height: 20),
            GradientButton(
              text: 'Add to Meal',
              onPressed: () {
                if (nameCtrl.text.trim().isEmpty) return;
                setState(() {
                  _items.add(
                    MealItem(
                      name: nameCtrl.text.trim(),
                      portionText: portionCtrl.text.trim(),
                      gramsEstimate: 120,
                      calories: double.tryParse(calCtrl.text) ?? 200,
                      proteinG: double.tryParse(pCtrl.text) ?? 10,
                      carbsG: double.tryParse(cCtrl.text) ?? 25,
                      fatG: double.tryParse(fCtrl.text) ?? 6,
                      fiberG: 2,
                    ),
                  );
                });
                Navigator.pop(ctx);
              },
            ),
          ],
        ),
      ),
    );
  }

  @override
  Widget build(BuildContext context) {
    final isDark = Theme.of(context).brightness == Brightness.dark;

    return Scaffold(
      appBar: AppBar(
        title: const Text(AppStrings.mealResult),
        actions: [
          IconButton(
            icon: const Icon(Icons.close_rounded),
            onPressed: _discardMeal,
          ),
        ],
      ),
      body: SafeArea(
        child: SingleChildScrollView(
          padding: const EdgeInsets.symmetric(horizontal: 20, vertical: 12),
          child: Column(
            crossAxisAlignment: CrossAxisAlignment.stretch,
            children: [
              // Photo Preview & Summary
              if (widget.localFile != null)
                ClipRRect(
                  borderRadius: BorderRadius.circular(20),
                  child: SizedBox(
                    height: 180,
                    width: double.infinity,
                    child: Image.file(
                      widget.localFile!,
                      fit: BoxFit.cover,
                    ),
                  ),
                ),
              const SizedBox(height: 16),

              // Meal Type & Confidence Row
              Row(
                mainAxisAlignment: MainAxisAlignment.spaceBetween,
                children: [
                  DropdownButton<String>(
                    value: _mealType,
                    dropdownColor: isDark ? AppColors.darkSurfaceElevated : Colors.white,
                    items: const [
                      DropdownMenuItem(value: 'breakfast', child: Text('Breakfast')),
                      DropdownMenuItem(value: 'lunch', child: Text('Lunch')),
                      DropdownMenuItem(value: 'dinner', child: Text('Dinner')),
                      DropdownMenuItem(value: 'snack', child: Text('Snack')),
                    ],
                    onChanged: (val) {
                      if (val != null) setState(() => _mealType = val);
                    },
                  ),
                  _buildConfidenceBadge(),
                ],
              ),
              const SizedBox(height: 12),

              // Nutritional Overview GlassCard
              GlassCard(
                child: Column(
                  children: [
                    Row(
                      mainAxisAlignment: MainAxisAlignment.spaceBetween,
                      children: [
                        const Text(
                          'Total Calories',
                          style: TextStyle(fontSize: 16, fontWeight: FontWeight.w600),
                        ),
                        Text(
                          Formatters.formatCalories(_totalCalories),
                          style: const TextStyle(
                            fontSize: 24,
                            fontWeight: FontWeight.w800,
                            color: AppColors.primaryGreen,
                          ),
                        ),
                      ],
                    ),
                    const SizedBox(height: 16),
                    Row(
                      children: [
                        Expanded(child: MacroChip.protein(_totalProtein)),
                        const SizedBox(width: 8),
                        Expanded(child: MacroChip.carbs(_totalCarbs)),
                        const SizedBox(width: 8),
                        Expanded(child: MacroChip.fat(_totalFat)),
                        const SizedBox(width: 8),
                        Expanded(child: MacroChip.fiber(_totalFiber)),
                      ],
                    ),
                  ],
                ),
              ),
              const SizedBox(height: 16),

              // Disclaimer
              Container(
                padding: const EdgeInsets.symmetric(horizontal: 14, vertical: 10),
                decoration: BoxDecoration(
                  color: Colors.amber.withValues(alpha: 0.12),
                  borderRadius: BorderRadius.circular(12),
                  border: Border.all(color: Colors.amber.withValues(alpha: 0.3)),
                ),
                child: const Row(
                  children: [
                    Icon(Icons.info_outline_rounded, color: Colors.amber, size: 18),
                    SizedBox(width: 10),
                    Expanded(
                      child: Text(
                        AppStrings.disclaimerShort,
                        style: TextStyle(
                          fontSize: 12,
                          fontWeight: FontWeight.w500,
                          color: Colors.amber,
                        ),
                      ),
                    ),
                  ],
                ),
              ),
              const SizedBox(height: 20),

              // Items List Header
              Row(
                mainAxisAlignment: MainAxisAlignment.spaceBetween,
                children: [
                  Text(AppStrings.itemsDetected, style: AppTextStyles.titleMedium(context)),
                  TextButton.icon(
                    icon: const Icon(Icons.add_rounded, size: 18),
                    label: const Text(AppStrings.addItem),
                    onPressed: _addItemDialog,
                  ),
                ],
              ),
              const SizedBox(height: 8),

              // Detected items cards
              ..._items.asMap().entries.map((entry) {
                final idx = entry.key;
                final item = entry.value;

                return GlassCard(
                  margin: const EdgeInsets.only(bottom: 10),
                  padding: const EdgeInsets.all(14),
                  onTap: () => _editItemDialog(idx),
                  child: Row(
                    children: [
                      Expanded(
                        child: Column(
                          crossAxisAlignment: CrossAxisAlignment.start,
                          children: [
                            Text(
                              item.name,
                              style: const TextStyle(
                                fontSize: 15,
                                fontWeight: FontWeight.w600,
                              ),
                            ),
                            const SizedBox(height: 3),
                            Text(
                              '${item.portionText} • ${item.gramsEstimate.round()}g',
                              style: TextStyle(
                                fontSize: 12,
                                color: isDark
                                    ? AppColors.darkTextSecondary
                                    : AppColors.lightTextSecondary,
                              ),
                            ),
                            const SizedBox(height: 4),
                            Text(
                              'P: ${Formatters.formatGrams(item.proteinG)}  C: ${Formatters.formatGrams(item.carbsG)}  F: ${Formatters.formatGrams(item.fatG)}',
                              style: const TextStyle(fontSize: 11, color: AppColors.primaryGreen),
                            ),
                          ],
                        ),
                      ),
                      Column(
                        crossAxisAlignment: CrossAxisAlignment.end,
                        children: [
                          Text(
                            Formatters.formatCalories(item.calories),
                            style: const TextStyle(
                              fontSize: 15,
                              fontWeight: FontWeight.w700,
                            ),
                          ),
                          const SizedBox(height: 4),
                          const Icon(Icons.edit_outlined, size: 16, color: Colors.white54),
                        ],
                      ),
                    ],
                  ),
                );
              }),
              const SizedBox(height: 24),

              // Save to Log and Discard Buttons
              GradientButton(
                text: AppStrings.saveToLog,
                icon: Icons.check_rounded,
                isLoading: _isSaving,
                onPressed: _isSaving ? null : _saveMeal,
              ),
              const SizedBox(height: 12),

              OutlinedButton(
                style: OutlinedButton.styleFrom(
                  minimumSize: const Size.fromHeight(50),
                  shape: RoundedRectangleBorder(borderRadius: BorderRadius.circular(16)),
                  side: const BorderSide(color: AppColors.error),
                ),
                onPressed: _isSaving ? null : _discardMeal,
                child: const Text(
                  AppStrings.discard,
                  style: TextStyle(color: AppColors.error, fontWeight: FontWeight.w600),
                ),
              ),
              const SizedBox(height: 20),
            ],
          ),
        ),
      ),
    );
  }

  Widget _buildConfidenceBadge() {
    Color color;
    String label;
    switch (_confidence.toLowerCase()) {
      case 'high':
        color = AppColors.primaryGreen;
        label = AppStrings.confidenceHigh;
        break;
      case 'low':
        color = AppColors.warning;
        label = AppStrings.confidenceLow;
        break;
      case 'medium':
      default:
        color = AppColors.primaryTeal;
        label = AppStrings.confidenceMedium;
        break;
    }

    return Container(
      padding: const EdgeInsets.symmetric(horizontal: 10, vertical: 4),
      decoration: BoxDecoration(
        color: color.withValues(alpha: 0.15),
        borderRadius: BorderRadius.circular(12),
        border: Border.all(color: color.withValues(alpha: 0.4)),
      ),
      child: Text(
        label,
        style: TextStyle(fontSize: 11, fontWeight: FontWeight.w600, color: color),
      ),
    );
  }
}
